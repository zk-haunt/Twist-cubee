#!/usr/bin/env python3
"""Generates Twist Cubee's launcher icons and sound effects.

Everything is produced from code so the artwork is reproducible and free of third-party assets:

  app/src/main/res/drawable/ic_launcher_{foreground,background,monochrome}.xml   adaptive icon
  app/src/main/res/mipmap-*/ic_launcher{,_round}.png                             legacy icons
  fastlane/metadata/android/en-US/images/icon.png                                512 px store icon
  app/src/main/res/raw/{turn,solved}.wav                                         sound effects

Usage:  python3 tools/generate_assets.py        (needs numpy)
"""
import math
import os
import struct
import wave
import zlib

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RES = os.path.join(ROOT, "app", "src", "main", "res")
STORE_ICON = os.path.join(ROOT, "fastlane", "metadata", "android", "en-US", "images", "icon.png")

# Face colors (U R F D L B) of the classic scheme, body color, background gradient.
FACE_RGB = {
    "U": (0xF5, 0xF5, 0xF5), "R": (0xD8, 0x12, 0x2A), "F": (0x00, 0xA5, 0x4F),
    "D": (0xFF, 0xD4, 0x00), "L": (0xFF, 0x6C, 0x00), "B": (0x10, 0x60, 0xD8),
}
BODY = (0x12, 0x14, 0x19)
BG_TOP = (0x22, 0x31, 0x55)
BG_BOTTOM = (0x09, 0x0E, 0x1B)
LIGHT = np.array([-0.35, 0.85, 0.40])
LIGHT = LIGHT / np.linalg.norm(LIGHT)


# --------------------------------------------------------------------------- 3D model


def rot_x(a):
    c, s = math.cos(a), math.sin(a)
    return np.array([[1, 0, 0], [0, c, -s], [0, s, c]])


def rot_y(a):
    c, s = math.cos(a), math.sin(a)
    return np.array([[c, 0, s], [0, 1, 0], [-s, 0, c]])


FACES = [  # name, normal, tangent, bitangent (tangent x bitangent = normal)
    ("U", (0, 1, 0), (1, 0, 0), (0, 0, -1)),
    ("R", (1, 0, 0), (0, 0, -1), (0, 1, 0)),
    ("F", (0, 0, 1), (1, 0, 0), (0, 1, 0)),
    ("D", (0, -1, 0), (1, 0, 0), (0, 0, 1)),
    ("L", (-1, 0, 0), (0, 0, 1), (0, 1, 0)),
    ("B", (0, 0, -1), (-1, 0, 0), (0, 1, 0)),
]


def shade(rgb, normal_world, ambient=0.50):
    k = ambient + (1 - ambient) * max(0.0, float(np.dot(normal_world, LIGHT)))
    return tuple(int(min(255, round(c * k))) for c in rgb)


def cube_polygons(twist_deg=24.0, yaw_deg=-42.0, pitch_deg=29.0, stickers_only=False):
    """Returns [(depth, rgb, [(x, y), ...])] for a 3x3 cube with its top layer twisted."""
    view = rot_x(math.radians(pitch_deg)) @ rot_y(math.radians(yaw_deg))
    twist = rot_y(math.radians(twist_deg))
    half, sticker = 0.47, 0.40
    polys = []
    for x in (-1, 0, 1):
        for y in (-1, 0, 1):
            for z in (-1, 0, 1):
                center = np.array([x, y, z], dtype=float)
                layer = twist if y == 1 else np.eye(3)
                for name, n, t, b in FACES:
                    n = np.array(n, float)
                    t = np.array(t, float)
                    b = np.array(b, float)
                    nw = layer @ n
                    nv = view @ nw
                    if nv[2] <= 1e-6:
                        continue  # back face
                    outward = float(np.dot(center, n)) == 1.0
                    quads = []
                    if not stickers_only:
                        quads.append((half, BODY, 0.0))
                    if outward:
                        quads.append((sticker, FACE_RGB[name], 0.002))
                    for size, rgb, lift in quads:
                        corners = []
                        for su, sv in ((-1, -1), (1, -1), (1, 1), (-1, 1)):
                            p = center + n * (half + lift) + t * su * size + b * sv * size
                            corners.append(view @ (layer @ p))
                        depth = float(np.mean([c[2] for c in corners])) + lift * 10
                        pts = [(float(c[0]), float(-c[1])) for c in corners]
                        polys.append((depth, shade(rgb, nw, 0.68 if rgb != BODY else 0.75), pts))
    polys.sort(key=lambda p: p[0])
    return polys


def fit(polys, cx, cy, radius):
    """Scales/translates polygons so the drawing is centered and fits in a circle of radius."""
    pts = [p for _, _, ps in polys for p in ps]
    mx = (min(p[0] for p in pts) + max(p[0] for p in pts)) / 2
    my = (min(p[1] for p in pts) + max(p[1] for p in pts)) / 2
    r = max(math.hypot(p[0] - mx, p[1] - my) for p in pts)
    s = radius / r
    return [(d, c, [((x - mx) * s + cx, (y - my) * s + cy) for x, y in ps]) for d, c, ps in polys]


# --------------------------------------------------------------------------- vector drawables


def hexcolor(c):
    return "#FF%02X%02X%02X" % c


def path_data(pts):
    return "M" + " L".join("%.2f,%.2f" % p for p in pts) + " Z"


def vector(paths, extra_ns=""):
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<!-- Generated by tools/generate_assets.py; do not edit by hand. -->\n'
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"%s\n'
        '    android:width="108dp"\n    android:height="108dp"\n'
        '    android:viewportWidth="108"\n    android:viewportHeight="108">\n%s\n</vector>\n'
    ) % (extra_ns, "\n".join(paths))


def write_vectors():
    drawable = os.path.join(RES, "drawable")
    polys = fit(cube_polygons(), 54, 54, 31)
    paths = ['    <path android:fillColor="%s" android:pathData="%s" />' % (hexcolor(c), path_data(p)) for _, c, p in polys]
    open(os.path.join(drawable, "ic_launcher_foreground.xml"), "w").write(vector(paths))

    mono = fit(cube_polygons(stickers_only=True), 54, 54, 31)
    paths = ['    <path android:fillColor="#FFFFFFFF" android:pathData="%s" />' % path_data(p) for _, _, p in mono]
    open(os.path.join(drawable, "ic_launcher_monochrome.xml"), "w").write(vector(paths))

    bg = (
        '    <path android:pathData="M0,0h108v108h-108z">\n'
        '        <aapt:attr name="android:fillColor">\n'
        '            <gradient android:type="linear" android:startX="54" android:startY="0"\n'
        '                android:endX="54" android:endY="108"\n'
        '                android:startColor="%s" android:endColor="%s" />\n'
        '        </aapt:attr>\n'
        '    </path>'
    ) % (hexcolor(BG_TOP), hexcolor(BG_BOTTOM))
    open(os.path.join(drawable, "ic_launcher_background.xml"), "w").write(
        vector([bg], extra_ns='\n    xmlns:aapt="http://schemas.android.com/aapt"'))

    for name in ("ic_launcher", "ic_launcher_round"):
        open(os.path.join(RES, "mipmap-anydpi-v26", name + ".xml"), "w").write(
            '<?xml version="1.0" encoding="utf-8"?>\n'
            '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
            '    <background android:drawable="@drawable/ic_launcher_background" />\n'
            '    <foreground android:drawable="@drawable/ic_launcher_foreground" />\n'
            '    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />\n'
            '</adaptive-icon>\n')


# --------------------------------------------------------------------------- raster icons


def convex_mask(xs, ys, poly):
    mask = np.ones(xs.shape, dtype=bool)
    n = len(poly)
    area = sum(poly[i][0] * poly[(i + 1) % n][1] - poly[(i + 1) % n][0] * poly[i][1] for i in range(n))
    sgn = 1 if area > 0 else -1
    for i in range(n):
        x0, y0 = poly[i]
        x1, y1 = poly[(i + 1) % n]
        mask &= ((x1 - x0) * (ys - y0) - (y1 - y0) * (xs - x0)) * sgn >= 0
    return mask


def render_icon(size, shape):
    ss = 4
    n = size * ss
    coords = (np.arange(n) + 0.5) / ss
    xs, ys = np.meshgrid(coords, coords)
    t = (ys / size)[..., None]
    rgb = np.array(BG_TOP, float) * (1 - t) + np.array(BG_BOTTOM, float) * t
    if shape == "round":
        inside = (xs - size / 2) ** 2 + (ys - size / 2) ** 2 <= (size * 0.48) ** 2
    elif shape == "square":
        m, rr = size * 0.04, size * 0.18
        cx = np.clip(xs, m + rr, size - m - rr)
        cy = np.clip(ys, m + rr, size - m - rr)
        inside = ((xs - cx) ** 2 + (ys - cy) ** 2 <= rr ** 2) & (xs >= m) & (xs <= size - m) & (ys >= m) & (ys <= size - m)
    else:
        inside = np.ones(xs.shape, dtype=bool)
    radius = size * (0.36 if shape != "full" else 0.40)
    for _, color, pts in fit(cube_polygons(), size / 2, size / 2, radius):
        x0 = max(0, int(min(p[0] for p in pts) * ss) - 1)
        x1 = min(n, int(max(p[0] for p in pts) * ss) + 2)
        y0 = max(0, int(min(p[1] for p in pts) * ss) - 1)
        y1 = min(n, int(max(p[1] for p in pts) * ss) + 2)
        if x1 <= x0 or y1 <= y0:
            continue
        m = convex_mask(xs[y0:y1, x0:x1], ys[y0:y1, x0:x1], pts) & inside[y0:y1, x0:x1]
        rgb[y0:y1, x0:x1][m] = color
    a = inside.astype(float)
    rgb = (rgb * a[..., None]).reshape(size, ss, size, ss, 3).sum(axis=(1, 3))
    a = a.reshape(size, ss, size, ss).sum(axis=(1, 3))
    color = np.where(a[..., None] > 0, rgb / np.maximum(a[..., None], 1e-9), 0)
    out = np.concatenate([color, (a / (ss * ss) * 255.0)[..., None]], axis=-1)
    return np.clip(np.round(out), 0, 255).astype(np.uint8)


def write_png(path, pixels):
    h, w, _ = pixels.shape
    raw = b"".join(b"\x00" + pixels[y].tobytes() for y in range(h))

    def chunk(tag, data):
        c = struct.pack(">I", len(data)) + tag + data
        return c + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF)

    png = b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, 6, 0, 0, 0))
    png += chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b"")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    open(path, "wb").write(png)


def write_pngs():
    for density, size in {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}.items():
        write_png(os.path.join(RES, "mipmap-" + density, "ic_launcher.png"), render_icon(size, "square"))
        write_png(os.path.join(RES, "mipmap-" + density, "ic_launcher_round.png"), render_icon(size, "round"))
    write_png(STORE_ICON, render_icon(512, "full"))


# --------------------------------------------------------------------------- sounds


def write_wav(path, samples, rate=44100):
    pcm = (np.clip(samples, -1, 1) * 32767).astype("<i2").tobytes()
    with wave.open(path, "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(rate)
        w.writeframes(pcm)


def write_sounds():
    rate = 44100
    rng = np.random.default_rng(1)
    # Turn: a short plastic tick (shaped noise burst) over a damped low knock.
    n = int(rate * 0.045)
    t = np.arange(n) / rate
    noise = rng.standard_normal(n)
    hp = np.zeros(n)
    px = py = 0.0
    for i in range(n):
        py = 0.85 * (py + noise[i] - px)
        px = noise[i]
        hp[i] = py
    lp = np.zeros(n)
    acc = 0.0
    for i in range(n):
        acc += 0.45 * (hp[i] - acc)
        lp[i] = acc
    snd = lp * np.exp(-t * 160) * 0.55 + np.sin(2 * math.pi * 210 * t) * np.exp(-t * 90) * 0.35
    snd *= np.minimum(1, t / 0.0015)
    write_wav(os.path.join(RES, "raw", "turn.wav"), snd / (np.max(np.abs(snd)) / 0.8), rate)

    # Solved: a bright major arpeggio with soft bell partials.
    n = int(rate * 1.3)
    t = np.arange(n) / rate
    out = np.zeros(n)
    for k, f in enumerate((523.25, 659.25, 783.99, 1046.50)):
        tt = t - k * 0.085
        env = np.where(tt >= 0, np.exp(-np.maximum(tt, 0) * 3.2) * np.minimum(1, np.maximum(tt, 0) / 0.004), 0)
        tone = np.sin(2 * math.pi * f * tt) + 0.35 * np.sin(4 * math.pi * f * tt) + 0.12 * np.sin(2 * math.pi * 3.01 * f * tt)
        out += tone * env * (0.9 if k < 3 else 1.1)
    write_wav(os.path.join(RES, "raw", "solved.wav"), out / (np.max(np.abs(out)) / 0.7), rate)


if __name__ == "__main__":
    write_vectors()
    write_pngs()
    write_sounds()
    print("assets written")
